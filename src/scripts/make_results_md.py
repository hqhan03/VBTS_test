def _wh(v):
    """해상도를 가로x세로로. 사다리에 없는 값(복제 중앙값)은 가장 가까운 단에 `~`."""
    v = int(round(float(v)))
    if v in _WH:
        return _WH[v]
    n = min(_WH, key=lambda k: abs(k - v))
    return f"~{_WH[n]}"


